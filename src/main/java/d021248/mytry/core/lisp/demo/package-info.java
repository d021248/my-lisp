///       d021248.mytry.core.lisp.list.Lisp} operations on eager lists
///   - [d021248.mytry.core.lisp.demo.LazyListDemo] – demonstrates infinite lazy sequences
///       via [d021248.mytry.core.lisp.list.Lazy] (primes, Fibonacci, etc.)
///   - [d021248.mytry.core.lisp.demo.SymbolicDemo] – shows the full symbolic differentiation
///       pipeline: parse → differentiate → simplify → evaluate
///   - [d021248.mytry.core.lisp.demo.TaylorDemo] – showcases Taylor series where all three
///       pillars (lazy lists, symbolic math, numerical evaluation) meet
///
/// @since 1.0
